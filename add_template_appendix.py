        ("3.1. Краткое описание и профиль деятельности", 1),
        ("3.2. Ключевые факты и цифры (год основания, численность, проекты)", 1),
        ("3.3. Компетенции и направления", 1),
        ("3.4. Клиенты и референс-проекты", 1),
        ("3.5. Партнёры и технологические альянсы", 1),
        ("3.6. Награды, сертификаты, рыночные позиции", 1),
        ("3.7. География деятельности", 1),
        ("", 0),
        ("4. Понимание задачи (Контекст проекта)", 0),
        ("4.1. Текущая ситуация у Заказчика", 1),
        ("4.2. Цели и задачи проекта", 1),
        ("4.3. Ожидаемые результаты", 1),
        ("", 0),
        ("5. Организационный объём и функциональные границы", 0),
        ("5.1. Организационные рамки проекта (юр. лица, площадки, подразделения)", 1),
        ("5.2. Цели проекта (детализация)", 1),
        ("5.3. Архитектура решения", 1),
        ("5.3.1. Технологическая платформа", 2),
        ("5.3.2. Инфраструктура и доступ", 2),
