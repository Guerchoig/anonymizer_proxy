from docx import Document
from docx.shared import Pt

def insert_section_before(doc, insert_before_idx, title, description_lines):
    """Вставляет раздел 'О документе' перед указанным параграфом"""
    target_para = doc.paragraphs[insert_before_idx]
    new_paragraphs = []
    
    # Заголовок
    p1 = doc.add_paragraph()
    if 'Heading 1' in [s.name for s in doc.styles]:
        p1.style = doc.styles['Heading 1']
    else:
        p1.style = doc.styles['Normal']
        run = p1.add_run()
        run.bold = True
        run.font.size = Pt(14)
    p1.text = title
    new_paragraphs.append(p1)
    
    # Пустой параграф
    new_paragraphs.append(doc.add_paragraph())
    
    # Описание
    for line in description_lines:
        p = doc.add_paragraph()
        p.text = line
        new_paragraphs.append(p)
    
    # Пустой параграф после
    new_paragraphs.append(doc.add_paragraph())
    
    # Перемещаем параграфы в нужное место (в правильном порядке)
    for new_p in new_paragraphs:
        target_para._element.addprevious(new_p._element)


