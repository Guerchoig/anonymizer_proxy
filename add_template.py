def add_template_appendix(doc, appendix_number):
    doc.add_paragraph()
    p_title = doc.add_paragraph(
        f"Приложение {appendix_number}. Шаблон структуры коммерческого предложения"
    )
    p_title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_title.runs[0].bold = True
    p_title.runs[0].font.size = Pt(14)
    doc.add_paragraph()
    for text, level in TEMPLATE:
        if text == "":
            doc.add_paragraph()
        else:
            p = doc.add_paragraph("    " * level + text)
            if level == 0 and p.runs:
                p.runs[0].bold = True
                p.runs[0].font.size = Pt(12)
            elif level == 1 and p.runs:
                p.runs[0].font.size = Pt(11)
            elif level == 2 and p.runs:
                p.runs[0].italic = True
                p.runs[0].font.size = Pt(11)
