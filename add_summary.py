import docx
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

def add_summary_to_doc(input_path, output_path, summary_text):
    """Добавляет резюме в конец документа"""
    doc = docx.Document(input_path)
    
    # Добавляем пустой параграф для отступа
    doc.add_paragraph()
    
    # Добавляем заголовок "РЕЗЮМЕ ДОКУМЕНТА"
    heading = doc.add_paragraph()
    heading_run = heading.add_run('РЕЗЮМЕ ДОКУМЕНТА')
    heading_run.bold = True
    heading_run.font.size = Pt(14)
    heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
    
    # Добавляем пустой параграф
    doc.add_paragraph()
    
    # Добавляем текст резюме
    summary_para = doc.add_paragraph(summary_text)
    summary_para.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    
    # Сохраняем результат
    doc.save(output_path)
    print(f"✓ Создан файл: {output_path}")

